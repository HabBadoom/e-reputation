"""Private object storage for Scanner files.

Two backends behind one interface:
  * `S3Storage` — any S3-compatible service (MinIO in development, an S3-compatible bucket at
    the EU host in production). The bucket must not allow anonymous access; files are only ever
    returned through the authenticated Scanner API.
  * `FilesystemStorage` — local directory, for development and tests only (refused in
    staging/production by the settings validator).

Keys are generated by the application (`scanner/<account>/<session>/<file>.<ext>`), never taken
from the client.
"""

import os
import re
import tempfile
from functools import lru_cache
from pathlib import Path
from typing import Protocol

from app.core.config import get_settings

_KEY = re.compile(r"^[a-z0-9][a-z0-9/_.-]{0,298}$")


class StorageError(Exception):
    pass


def _check_key(key: str) -> str:
    if not _KEY.fullmatch(key) or ".." in key or "//" in key:
        raise StorageError("invalid storage key")
    return key


class Storage(Protocol):
    def put(self, key: str, data: bytes, content_type: str) -> None: ...
    def get(self, key: str) -> bytes: ...
    def delete(self, key: str) -> None: ...


class FilesystemStorage:
    def __init__(self, root: str):
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        p = (self.root / _check_key(key)).resolve()
        if self.root not in p.parents:
            raise StorageError("invalid storage key")
        return p

    def put(self, key: str, data: bytes, content_type: str) -> None:
        p = self._path(key)
        p.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        fd, tmp = tempfile.mkstemp(dir=p.parent)
        try:
            with os.fdopen(fd, "wb") as f:
                f.write(data)
            os.chmod(tmp, 0o600)
            os.replace(tmp, p)
        except BaseException:
            Path(tmp).unlink(missing_ok=True)
            raise

    def get(self, key: str) -> bytes:
        try:
            return self._path(key).read_bytes()
        except FileNotFoundError as e:
            raise StorageError("object not found") from e

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


class S3Storage:
    def __init__(self, *, endpoint_url: str, region: str, bucket: str, access_key: str,
                 secret_key: str):
        import boto3
        from botocore.config import Config

        self.bucket = bucket
        self.client = boto3.client(
            "s3", endpoint_url=endpoint_url or None, region_name=region,
            aws_access_key_id=access_key or None, aws_secret_access_key=secret_key or None,
            config=Config(signature_version="s3v4", s3={"addressing_style": "path"},
                          retries={"max_attempts": 3, "mode": "standard"},
                          connect_timeout=5, read_timeout=30))

    def put(self, key: str, data: bytes, content_type: str) -> None:
        try:
            self.client.put_object(Bucket=self.bucket, Key=_check_key(key), Body=data,
                                   ContentType=content_type)
        except Exception as e:  # botocore errors: never leak credentials or endpoints upward
            raise StorageError("could not store the file") from e

    def get(self, key: str) -> bytes:
        try:
            return self.client.get_object(Bucket=self.bucket, Key=_check_key(key))["Body"].read()
        except Exception as e:
            raise StorageError("could not read the file") from e

    def delete(self, key: str) -> None:
        try:
            self.client.delete_object(Bucket=self.bucket, Key=_check_key(key))
        except Exception as e:
            raise StorageError("could not delete the file") from e


@lru_cache
def get_storage() -> Storage:
    s = get_settings()
    if s.storage_backend == "s3":
        return S3Storage(endpoint_url=s.storage_endpoint_url, region=s.storage_region,
                         bucket=s.storage_bucket,
                         access_key=s.storage_access_key.get_secret_value(),
                         secret_key=s.storage_secret_key.get_secret_value())
    return FilesystemStorage(s.storage_filesystem_root)
